import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdir,writeFile,readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const requireTools=createRequire(path.join(root,'../tools/mcp-node/package.json'));
const {chromium}=requireTools('playwright');
const artifacts=path.join(root,'artifacts');await mkdir(artifacts,{recursive:true});
const primaryKeyPath=path.join(root,'data/wokwi-bridge-key');
const primaryKeyBefore=await readFile(primaryKeyPath,'utf8').catch(()=>null);
const processes=[spawn(process.execPath,['server/http.mjs'],{cwd:root,env:{...process.env,PARKING_CREATOR_KEY:'isolated-browser-creator',PARKING_PORT:'4186',PARKING_DB:':memory:',PARKING_AUTO_TICK:'0'},stdio:'pipe'}),spawn(process.execPath,['node_modules/vite/bin/vite.js','--host','127.0.0.1','--port','5185','--strictPort'],{cwd:root,env:{...process.env,PARKING_API_URL:'http://127.0.0.1:4186'},stdio:'pipe'})];
for(const child of processes){child.stdout.on('data',()=>{});child.stderr.on('data',()=>{});}
async function wait(url){for(let n=0;n<60;n++){try{if((await fetch(url)).ok)return;}catch{}await new Promise(resolve=>setTimeout(resolve,250));}throw new Error('Test service unavailable: '+url);}
let browser;
try{
  await Promise.all([wait('http://127.0.0.1:4186/api/state'),wait('http://127.0.0.1:5185')]);
  assert.ok((await readFile(primaryKeyPath,'utf8').catch(()=>null))===primaryKeyBefore,'Isolated API must not replace the running demo bridge credential');
  browser=await chromium.launch({headless:true});
  const context=await browser.newContext({viewport:{width:1600,height:1000},recordVideo:{dir:artifacts,size:{width:1600,height:1000}}});
  await context.addInitScript(()=>sessionStorage.setItem('baypilot-creator-key','isolated-browser-creator'));
  const page=await context.newPage();const pageErrors=[];page.on('pageerror',error=>pageErrors.push(error.message));
  await page.goto('http://127.0.0.1:5185/?view=overview');
  assert((await page.locator('body').innerText()).includes('Parking overview'),'Parking overview screen is missing');
  await page.screenshot({path:path.join(artifacts,'overview.png'),fullPage:true});
  await page.getByRole('button',{name:'Resident app',exact:true}).click();
  await page.getByRole('button',{name:'Arrive at gate',exact:true}).click();
  await page.getByRole('button',{name:'Advance 3s',exact:true}).click();
  await page.getByRole('button',{name:'Park my car',exact:true}).click();
  await page.getByRole('button',{name:'Advance 3s',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[data-testid="resident-state"]')?.textContent?.includes('OCCUPIED_PARKED'));
  await page.screenshot({path:path.join(artifacts,'resident-parked.png'),fullPage:true});
  await page.getByRole('button',{name:'Leave my bay',exact:true}).click();
  await page.getByRole('button',{name:'Advance 15s',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[data-testid="resident-state"]')?.textContent?.includes('LOCKED_VACANT'));
  await page.getByRole('button',{name:'Workflows',exact:true}).click();
  await page.getByLabel('Require host approval').check();
  await page.getByRole('button',{name:'Publish workflow',exact:true}).click();
  await page.waitForFunction(()=>document.body.innerText.includes('Version 2'));
  await page.getByRole('button',{name:'Guardhouse',exact:true}).click();
  await page.getByLabel('Guest name').fill('Demo Contractor');
  await page.getByRole('button',{name:'Register visitor',exact:true}).click();
  await page.getByRole('button',{name:'Record host approval',exact:true}).click();
  await page.getByRole('button',{name:'Hardware lab',exact:true}).click();
  await page.getByLabel('Device bay').selectOption('V-01');
  await page.getByRole('button',{name:'Inject motor jam',exact:true}).click();
  await page.getByRole('button',{name:'Guardhouse',exact:true}).click();
  await page.getByRole('button',{name:'Assign bay',exact:true}).click();
  await page.getByRole('button',{name:'Advance 3s',exact:true}).click();
  await page.waitForFunction(()=>document.body.innerText.includes('FAULT'));
  await page.screenshot({path:path.join(artifacts,'guard-fault.png'),fullPage:true});
  assert.equal(await page.getByRole('button',{name:'Assign temporary bay',exact:true}).count(),1,'Guard fallback action is missing');
  await page.getByRole('button',{name:'Assign temporary bay',exact:true}).click();
  await page.getByRole('button',{name:'Advance 3s',exact:true}).click();
  await page.waitForFunction(()=>document.body.innerText.includes('T-01')&&document.body.innerText.includes('READY'));
  await page.getByRole('button',{name:'Hardware lab',exact:true}).click();
  await page.screenshot({path:path.join(artifacts,'hardware-lab.png'),fullPage:true});
  assert.equal(pageErrors.length,0,pageErrors.join('\n'));
  const video=page.video();await context.close();await video.saveAs(path.join(artifacts,'demo-walkthrough.webm'));
  await writeFile(path.join(artifacts,'browser-results.json'),JSON.stringify({passed:true,scenarios:['resident arrival/park/departure','policy publish','host approval','jam/incident/temporary fallback'],pageErrors},null,2));
  console.log('Browser journeys passed: resident arrival/park/departure, policy publication, host approval, jam/incident/temporary fallback.');
}finally{await browser?.close();for(const child of processes)child.kill();}
